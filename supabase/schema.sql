-- Ausencia de registro significa "disponible".
-- Este trigger protege también el backend: aunque alguien altere React,
-- no puede pedir un producto u opción marcada como no disponible en la sucursal.
create or replace function public.validate_order_item_branch_availability()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
declare
  v_branch text;
  v_custom jsonb;
  v_template uuid;
  v_option text;
begin
  select o.branch_id into v_branch
  from public.orders o
  where o.id = new.order_id;

  if v_branch is null then
    raise exception 'No se pudo determinar la sucursal del pedido';
  end if;

  if exists (
    select 1
    from public.product_branch_availability pba
    where pba.product_id = new.product_id
      and pba.branch_id = v_branch
      and pba.available = false
  ) then
    raise exception 'Este producto no está disponible en la sucursal seleccionada';
  end if;

  for v_custom in
    select * from jsonb_array_elements(coalesce(new.customizations,'[]'::jsonb))
  loop
    v_template := nullif(v_custom->>'template_id','')::uuid;
    v_option := nullif(v_custom->>'option_id','');

    if v_template is not null and v_option is not null and exists (
      select 1
      from public.customization_option_branch_availability coba
      where coba.template_id = v_template
        and coba.option_id = v_option
        and coba.branch_id = v_branch
        and coba.available = false
    ) then
      raise exception 'Una opción seleccionada ya no está disponible en esta sucursal';
    end if;
  end loop;

  return new;
end;
$$;

drop trigger if exists trg_validate_order_item_branch_availability on public.order_items;
create trigger trg_validate_order_item_branch_availability
before insert or update on public.order_items
for each row execute function public.validate_order_item_branch_availability();


-- ===== v18 rewards directo al carrito =====
-- KYO v18 — Rewards van directo al carrito.
-- Ejecutar UNA sola vez después de v17.
--
-- 250 puntos -> 4 Spring Rolls directo al carrito.
-- 6 pedidos -> cualquier rollo de subcategoría "Clásicos", con personalizaciones gratis.
-- Si el cliente quita un reward del carrito antes de ordenar, cancel_reward_voucher()
-- devuelve los 250 puntos o los 6 sellos.

create or replace function public.cancel_reward_voucher(p_voucher_id uuid)
returns boolean
language plpgsql
security definer
set search_path=public
as $$
declare
  v_user uuid:=auth.uid();
  v_voucher public.reward_vouchers%rowtype;
begin
  if v_user is null then raise exception 'Debes iniciar sesión'; end if;

  select rv.* into v_voucher
  from public.reward_vouchers rv
  where rv.id=p_voucher_id
    and rv.user_id=v_user
    and rv.status='available'
  for update;

  if not found then
    return false;
  end if;

  if v_voucher.reward_type='spring_rolls' then
    update public.profiles
      set reward_points=reward_points+250
      where id=v_user;
  elsif v_voucher.reward_type='free_roll' then
    update public.profiles
      set reward_order_stamps=reward_order_stamps+6
      where id=v_user;
  else
    raise exception 'Tipo de reward inválido';
  end if;

  delete from public.reward_vouchers
  where id=v_voucher.id;

  return true;
end;
$$;

revoke all on function public.cancel_reward_voucher(uuid) from public;
grant execute on function public.cancel_reward_voucher(uuid) to authenticated;


